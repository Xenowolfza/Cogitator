export function factionById(id: string): Faction | undefined {
  return FACTIONS.find((f) => f.id === id);
}

export function extrasFor(list: { factionId: string; extraDetachments?: Record<string, Detachment[]> }): Detachment[] {
  return list.extraDetachments?.[list.factionId] ?? [];
}

export function detachmentById(factionId: string, detachmentId: string, extras: Detachment[] = []) {
  const faction = factionById(factionId);
  const all = [...(faction?.detachments ?? []), ...extras];
  return all.find((d) => d.id === detachmentId) ?? faction?.detachments[0];
}
